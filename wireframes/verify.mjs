import {createRequire} from 'node:module';
import {mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const bundle=process.env.CHAP_EHSAN_NODE_PACKAGES;
if(!bundle)throw new Error('Set CHAP_EHSAN_NODE_PACKAGES to the bundled node_modules directory.');
const require=createRequire(path.join(bundle,'package.json'));
const {chromium}=require('playwright');
const here=path.dirname(fileURLToPath(import.meta.url));
const out=path.join(here,'qa');await mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1280,height:1000},colorScheme:'light'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const pages=['index.html','index-02-banner.html','index-03-upload.html','index-04-checkout.html','index-05-result.html','index-06-tracking.html','index-07-poster.html','index-08-plot.html','index-09-sticker.html','index-10-exhibition.html','index-11-flag.html','index-12-admin.html','index-13-guide.html','index-14-contact.html','index-map.html'];
const report={pages:[],checks:[],runtimeErrors:errors};
for(const width of [1280,390,320]){
 await page.setViewportSize({width,height:1000});
 for(const name of pages){
  const response=await page.goto('http://127.0.0.1:4173/'+name);
  if(response.status()!==200)throw new Error('Failed page '+name);
  const layout=await page.evaluate(()=>({visible:[...document.querySelectorAll('[data-page]')].filter(x=>!x.hidden).length,width:document.documentElement.scrollWidth,viewport:innerWidth,missingIcons:document.querySelectorAll('i[data-lucide]').length}));
  if(layout.visible!==1||layout.width>width+1||layout.missingIcons)throw new Error(JSON.stringify({name,width,layout}));
  report.pages.push({name,width,status:'passed'});
 }
}
await page.setViewportSize({width:1280,height:1000});await page.goto('http://127.0.0.1:4173/');
await page.screenshot({path:path.join(out,'home-desktop.png'),fullPage:true});
await page.locator('[data-page="home"] a[data-go="banner"]').first().click();
await page.locator('#ep-width').fill('۵۰');await page.locator('#ep-height').fill('۲۰۰');await page.locator('#ep-quantity').fill('۲');
if(!(await page.locator('#ep-area').textContent()).includes('۱ مترمربع'))throw new Error('Persian dimension entry failed');
await page.locator('#ep-quantity').fill('1.5');await page.locator('#ep-banner-form button[type="submit"]').click();
if(!(await page.locator('#ep-banner-error').isVisible()))throw new Error('Invalid quantity accepted');
await page.locator('#ep-quantity').fill('۲');await page.locator('#ep-banner-form button[type="submit"]').click();
if(!(await page.locator('[data-page="upload"]').isVisible()))throw new Error('Banner continuation failed');
await page.locator('#ep-file').setInputFiles({name:'design-demo.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4\n% demo-only\n')});
await page.locator('#ep-use-demo-file').click();
if(!(await page.locator('#ep-checkout-file').textContent()).includes('design-demo.pdf'))throw new Error('File metadata not carried');
await page.locator('input[name="delivery"][value="shipping"]').check();
if(!(await page.locator('#ep-address-field').isVisible()))throw new Error('Shipping address not shown');
await page.locator('[data-page="checkout"] [data-go="result"]').click();
await page.locator('[data-page="result"] [data-go="tracking"]').click();
await page.locator('#ep-tracking-form button').click();
if(!(await page.locator('#ep-tracking-details').isVisible()))throw new Error('Tracking state failed');
report.checks.push('Persian digits; geometric area only; invalid quantity; banner-upload-checkout-result-tracking; file metadata; delivery state');
await page.goto('http://127.0.0.1:4173/index-07-poster.html');
await page.locator('[data-choice="چاپ و فوم‌برد"]').click();
if((await page.locator('[data-choice-title="poster"]').textContent())!=='چاپ و فوم‌برد')throw new Error('Poster selection failed');
await page.goto('http://127.0.0.1:4173/index-12-admin.html');await page.locator('[data-admin-tab="prices"]').click();
if(!(await page.locator('#ep-admin-prices').isVisible()))throw new Error('Admin tab failed');
report.checks.push('Poster choice; admin tariffs tab');
await page.setViewportSize({width:390,height:844});await page.goto('http://127.0.0.1:4173/');await page.screenshot({path:path.join(out,'home-mobile.png'),fullPage:true});
await page.goto('http://127.0.0.1:4173/index-02-banner.html');await page.screenshot({path:path.join(out,'banner-mobile.png'),fullPage:true});
await page.emulateMedia({colorScheme:'dark'});await page.goto('http://127.0.0.1:4173/');
const forcedLight=await page.locator('#ehsan-preview-v02').evaluate(el=>({background:getComputedStyle(el).backgroundColor,scheme:getComputedStyle(el).colorScheme}));
if(forcedLight.background!=='rgb(255, 255, 255)'||forcedLight.scheme!=='light')throw new Error('Fixed light mode failed');
