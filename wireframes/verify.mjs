if(await page.locator('i[data-lucide]').count())throw new Error('Offline icons missing');
await page.locator('[data-page="home"] [data-go="banner"]').click();
if(!(await page.locator('[data-page="banner"]').isVisible()))throw new Error('Offline navigation failed');
report.checks.push('Fixed light mode under dark system; offline icons and page navigation');
if(errors.length)throw new Error(errors.join('\n'));
await writeFile(path.join(out,'verification.json'),JSON.stringify(report,null,2));
await browser.close();console.log('45 page/viewport checks and prototype interaction checks passed; screenshots saved.');
